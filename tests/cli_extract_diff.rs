// ---------------------------------------------------------------------------
// Error paths (CLI_CONTRACT.md §8): a bad op input is a nonzero exit + a
// viprs-side message substring, never a panic/abort and never vips stderr text.
// ---------------------------------------------------------------------------

#[test]
fn extract_area_out_of_bounds_is_a_clean_error() {
    if skip_if_no_cli("extract_area_oob") {
        return;
    }
    let out = out_path("extract_area_oob.png");
    // A 20x20 rectangle at (10,10) does not fit the 16x16 input.
    let res = run_viprs(&[
        "extract_area",
        &fx(RGB),
        out.to_str().unwrap(),
        "10",
        "10",
        "20",
        "20",
    ]);
    assert!(
        !res.status.success(),
        "an out-of-bounds extract_area must exit nonzero"
    );
    let stderr = String::from_utf8_lossy(&res.stderr);
    assert!(
        stderr.contains("out of bounds"),
        "expected a viprs-side out-of-bounds message, got stderr: {stderr}"
    );
}

#[test]
fn extract_area_negative_coord_is_a_clean_error() {
    if skip_if_no_cli("extract_area_neg") {
        return;
    }
    let out = out_path("extract_area_neg.png");
    // vips's LEFT admits the signed gint range at parse; the core geometry is
    // u32-only, so a negative coordinate is a typed exit-1 error — NEVER a
    // u32::try_from abort (CLI_CONTRACT.md §8).
    let res = run_viprs(&[
        "extract_area",
        &fx(RGB),
        out.to_str().unwrap(),
        "-1",
        "0",
        "2",
        "2",
    ]);
    assert!(
        !res.status.success(),
        "a negative extract_area coordinate must exit nonzero"
    );
    let stderr = String::from_utf8_lossy(&res.stderr);
    assert!(
        stderr.contains("must be >= 0"),
        "expected a viprs-side negative-coordinate message, got stderr: {stderr}"
    );
}
