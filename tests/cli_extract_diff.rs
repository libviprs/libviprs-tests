//! CLI-DIFFERENTIAL suite — extract / geometry-placement family (a per-family
//! Wave-2 lane, CLI_CONTRACT.md §7, OP_MAP.md extract section).
//!
//! Each test runs `viprs <op> …` on the COMMON committed inputs under
//! `tests/fixtures/cli/extract/` and decode-compares its output against the
//! COMMITTED vips 8.18.4 reference at the op's §5 tolerance. The suite NEVER
//! runs vips: references are generated offline by `tools/gen_cli_expected.sh`
//! and committed. This cell copies the bands / morphology differential cells
//! exactly — including the skip-guard / `VIPRS_REQUIRE_CLI` discipline.
//!
//! Every extract op is oracle class **EXACT** (integer-in / integer-out,
//! decode-compare tol 0) **except `smartcrop --interesting entropy`**, which is
//! **GOLDEN-ONLY**: vips's entropy strategy makes a DIFFERENT discrete
//! crop-window choice than the core on the small committed input (measured
//! max-abs-diff 136 — a wholesale different region, not a tolerance), so there
//! is no meaningful cross-oracle. That reference is generated by `viprs` itself
//! (the strategy is deterministic across runs) and the test is a regression pin
//! that SAYS SO (CLI_CONTRACT.md §5 GOLDEN-ONLY). Every other strategy —
//! `centre`/`low`/`high` (pure geometry) and `attention` (the saliency pipeline,
//! which lands on the vips pixel and crops a region distinct from low/high) — is
//! a genuine EXACT vips differential.
//!
//! Every reference is an integer uchar raster with a clean interpretation
//! (1-band, or sRGB-tagged 3-band), so all outputs round-trip losslessly through
//! PNG (no b-w-multiband promotion, no ≥5-band carrier).
//!
//! If the `libviprs-cli` sibling is not checked out (the default CI `test` job
//! and the Docker gate clone only the core counterpart), every test SKIPS with a
//! clear message rather than failing — the dedicated `cli-differential` CI job
//! lays the CLI down and actually exercises these (CLI_CONTRACT.md §7).

mod common;

use std::path::PathBuf;
use std::sync::OnceLock;

use common::cli::{cli_available, cli_fixture, decode_compare, run_viprs, run_viprs_ok};

use tempfile::TempDir;

/// EXACT oracle class: bit-exact decode comparison (CLI_CONTRACT.md §5). Every
/// extract op is integer-in / integer-out — including `smartcrop attention`.
const EXACT: f64 = 0.0;

/// GOLDEN-ONLY pin tolerance for `smartcrop --interesting entropy`: bit-exact
/// against a committed `viprs`-generated reference (NOT vips — no cross-oracle;
/// see the module header). A regression pin, not a cross-implementation check.
const GOLDEN: f64 = 0.0;

/// Skip-guard: `true` (with a printed reason) when the CLI sibling is absent.
///
/// When `$VIPRS_REQUIRE_CLI=1` (the dedicated `cli-differential` CI job) an
/// absent sibling instead PANICS inside [`cli_available`], so this never returns
/// `true` there — a would-be silent skip becomes a hard failure.
fn skip_if_no_cli(test: &str) -> bool {
    if cli_available() {
        return false;
    }
    eprintln!(
        "SKIP {test}: libviprs-cli sibling not checked out \
         (set $VIPRS_CLI_DIR / $VIPRS_BIN, or run in the cli-differential job)."
    );
    true
}

/// Absolute path to a fresh output file inside a **process-lifetime** temp dir
/// (one [`TempDir`] reused for every case, reclaimed at process exit).
fn out_path(name: &str) -> PathBuf {
    static DIR: OnceLock<TempDir> = OnceLock::new();
    let dir = DIR.get_or_init(|| tempfile::tempdir().expect("create temp dir"));
    dir.path().join(name)
}

