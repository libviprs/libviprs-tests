// ---------------------------------------------------------------------------
// Error path: a float `.v` input must be a typed exit-1 error, NOT a panic
// (the core histogram ops' read_flat aborts on a float raster — the CLI guards
// it, bands B2 / CLI_CONTRACT.md §8).
// ---------------------------------------------------------------------------

#[test]
fn hist_find_rejects_float_input_without_panicking() {
    if skip_if_no_cli("hist_find_float_reject") {
        return;
    }
    // hist_norm_expected.v is a uchar histogram; build a float input instead by
    // casting gray to float via viprs itself, then feed it to hist_find.
    let float_in = out_path("float_in.v");
    run_viprs_ok(&["cast", &fx(GRAY), float_in.to_str().unwrap(), "float"]);
    let out = out_path("float_out.v");
    let output = common::cli::run_viprs(&[
        "hist_find",
        float_in.to_str().unwrap(),
        out.to_str().unwrap(),
    ]);
    assert!(
        !output.status.success(),
        "hist_find on a float raster must exit non-zero, not succeed"
    );
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(
        stderr.contains("integer image"),
        "expected a typed 'integer image' error, got stderr: {stderr}"
    );
}

/// Read a committed text fixture verbatim (trimmed by the caller). Used for the
/// boolean `hist_ismonotonic` references, which are not float-parseable.
fn read_string_fixture(rel: &str) -> String {
    let path = cli_fixture(rel);
    std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("cannot read fixture {}: {e}", path.display()))
}
