/// Convenience: the absolute string path of a committed fixture.
fn fx(rel: &str) -> String {
    cli_fixture(rel).to_str().unwrap().to_string()
}

/// Normalise vips's / viprs's boolean print form (`TRUE`/`FALSE`, or a `1`/`0`)
/// to a Rust `bool`, so the monotonicity scalar can be compared as the boolean
/// it is rather than parsed as a float (`TRUE` is not an `f64`).
fn parse_bool(s: &str) -> bool {
    let t = s.trim();
    match t.to_ascii_uppercase().as_str() {
        "TRUE" | "1" => true,
        "FALSE" | "0" => false,
        other => panic!("not a boolean scalar: {other:?}"),
    }
}

