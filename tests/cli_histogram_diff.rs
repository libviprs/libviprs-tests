//! CLI-DIFFERENTIAL suite — histogram family (a per-family Wave-2 lane,
//! CLI_CONTRACT.md §7, OP_MAP.md histogram section).
//!
//! Each test runs `viprs <op> …` on the COMMON committed inputs under
//! `tests/fixtures/cli/histogram/` and decode-compares its output against the
//! COMMITTED vips 8.18.4 reference at the op's §5 tolerance. The suite NEVER
//! runs vips: references are generated offline by `tools/gen_cli_expected.sh`
//! and committed. This cell copies the bands reference cell
//! (`cli_bands_diff.rs`) exactly — including the skip-guard /
//! `VIPRS_REQUIRE_CLI` discipline.
//!
//! # Oracle classes (measured, honest — OP_MAP.md + this wave's investigation)
//!
//! * **EXACT** (decode-compare tol 0): `hist_find` (+ `--band 0`, full range),
//!   `hist_find_indexed`, `hist_find_ndim`, `hist_cum`, `maplut`, and the
//!   boolean `hist_ismonotonic`. The count-producing ops write a **ushort**
//!   histogram where vips writes **uint**, so the generator casts the vips
//!   reference to ushort (a lossless narrowing while no count saturates); the
//!   two then agree bit-for-bit. `hist_find` matches only where the data reaches
//!   255 — vips trims trailing-zero bins to width max+1, the core keeps the full
//!   256 (a representational trim, not a count divergence). Count/LUT/histogram
//!   outputs are carried as the native `.v` container (vips tags them
//!   `histogram`, which pngsave has no colour route for — the `identity`
//!   situation); `hist_equal`/`maplut` write a plain b-w image → PNG.
//! * **BOUNDED-TOL**: `hist_norm` (≤1 LSB cumulative-norm rounding, measured
//!   max-abs-diff 1), `hist_equal` (≤1 LSB equalisation-LUT rounding, measured
//!   max-abs-diff 1), and the floating `hist_entropy` scalar (relative eps 1e-6).
//! * **GOLDEN-ONLY** (NO vips cross-oracle — the core genuinely diverges from
//!   vips; see the open questions in the wave report): `hist_match`,
//!   `hist_plot`, `hist_local`, and `percent`. Each reference is generated by
//!   `viprs` itself (deterministic) and the test is a **regression pin** locking
//!   the current core behaviour, NOT a parity claim. The divergences are real
//!   and MEASURED (not hidden by input choice):
//!   - `hist_match`: vips emits a `uint` LUT, the core a `uchar` index LUT; the
//!     mappings differ wholesale (measured max-abs-diff 254).
//!   - `hist_plot`: the core plots `max+1` rows, vips `max` rows (a systematic
//!     off-by-one in the graph height → dimensions never match).
//!   - `hist_local`: the core's sliding-window / border algorithm matches vips
//!     only for a 3×3 window; larger windows diverge (measured max-abs-diff 51
//!     at 5×5) and the CLAHE `--max-slope` path diverges further (60). We do NOT
//!     cherry-pick the coincidental 3×3 match (that would hide the divergence).
//!   - `percent`: the core returns "the smallest value whose cumulative count
//!     reaches P%" (at-or-below); vips returns "the threshold above which P% of
//!     pixels lie". The definitions differ (measured core = vips − 2 on a dense
//!     ramp), so there is no clean cross-oracle.
//!
//! If the `libviprs-cli` sibling is not checked out (the default CI `test` job
//! and the Docker gate clone only the core counterpart), every test SKIPS with
//! a clear message rather than failing — the dedicated `cli-differential` CI job
//! lays the CLI down and actually exercises these (CLI_CONTRACT.md §7).

