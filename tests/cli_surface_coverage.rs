/// The readers find what is definitely there, so an empty problem list means
/// covered rather than "read nothing".
fn sanity(core: &Core, cli: &Cli) {
    let features = manifest::feature_names(&core.manifest);
    for want in ["pdfium", "packfile", "jxl"] {
        assert!(
            features.iter().any(|f| f == want),
            "positive control: the core's [features] should declare `{want}`, read {features:?}"
        );
    }
    let modules = declared_modules(&core.lib_rs);
    assert!(
        modules.iter().filter(|(_, p)| *p).count() >= 40
            && modules.iter().any(|(m, p)| m == "arithmetic" && *p),
        "positive control: lib.rs should declare dozens of public modules, arithmetic \
         among them, read {modules:?}"
    );
    let arith = pub_fns(
        core.modules
            .get("arithmetic")
            .map(String::as_str)
            .unwrap_or(""),
    );
    assert!(
        arith.len() >= 100,
        "positive control: arithmetic.rs has well over 100 pub fns, read {}",
        arith.len()
    );
    let sections = op_map_sections(&cli.op_map);
    for want in ["arithmetic", "colour", "foreign", "raster_ops"] {
        assert!(
            sections.contains_key(want),
            "positive control: OP_MAP.md should have a `{want}` section, read {:?}",
            sections.keys().collect::<Vec<_>>()
        );
    }
    let builtins = cli_builtins(&cli.main_rs);
    for want in ["pyramid", "features", "test-image"] {
        assert!(
            builtins.contains(want),
            "positive control: the cli's enum Command should have `{want}`, read {builtins:?}"
        );
    }
    let listed = cli_listed_features(&cli.features_rs);
    assert!(
        listed.contains("pdfium") && listed.contains("jxl"),
        "positive control: src/features.rs FEATURES should list pdfium and jxl, read {listed:?}"
    );
}

/// `viprs features --json` still speaks the version this guard reads its
/// `FEATURES` table as, and prints nothing that table lacks.
///
/// The guard reads the table rather than the binary because the binary only
/// prints what one build has. This test is what ties the two together: if
/// the output grows a `"v": 2`, someone has changed what the listing means,
/// and the guard has to be re-read before it is trusted again.
#[test]
fn viprs_features_json_is_the_shape_the_guard_reads() {
    if !cli_source_available() {
        return;
    }
    let out = common::cli::run_viprs(&["features", "--json"]);
    assert!(
        out.status.success(),
        "`viprs features --json` failed: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    let json: serde_json::Value = serde_json::from_slice(&out.stdout).unwrap_or_else(|e| {
        panic!(
            "`viprs features --json` printed something that is not JSON ({e}): {}",
            String::from_utf8_lossy(&out.stdout)
        )
    });
    assert_eq!(
        json["v"],
        serde_json::json!(1),
        "`viprs features --json` is no longer format version 1: {json}"
    );
    let listed = cli_listed_features(&load_cli().features_rs);
    let printed = json["features"]
        .as_array()
        .unwrap_or_else(|| panic!("`features` is not an array: {json}"));
    for name in printed {
        let name = name
            .as_str()
            .unwrap_or_else(|| panic!("a feature that is not a string: {json}"));
        assert!(
            listed.contains(name),
            "`viprs features --json` printed `{name}`, which src/features.rs FEATURES \
             does not list ({listed:?})"
        );
    }
}

