/// What the guard needs from the core.
#[derive(Clone)]
struct Core {
    manifest: String,
    lib_rs: String,
    /// Source per declared module (a directory module is its files joined).
    modules: BTreeMap<String, String>,
}

/// What the guard needs from the CLI.
#[derive(Clone)]
struct Cli {
    manifest: String,
    features_rs: String,
    main_rs: String,
    op_map: String,
}

fn core_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../libviprs")
}

fn read(path: &Path) -> String {
    std::fs::read_to_string(path).unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()))
}

/// Every `.rs` file under `dir`, sorted, so a directory module reads the same
/// on every machine.
fn rust_files(dir: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let mut stack = vec![dir.to_path_buf()];
    while let Some(d) = stack.pop() {
        let entries =
            std::fs::read_dir(&d).unwrap_or_else(|e| panic!("cannot list {}: {e}", d.display()));
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                stack.push(path);
            } else if path.extension().is_some_and(|x| x == "rs") {
                out.push(path);
            }
        }
    }
    out.sort();
    out
}

fn load_core() -> Core {
    let dir = core_dir();
    let lib_rs = read(&dir.join("src/lib.rs"));
    let mut modules = BTreeMap::new();
    for (name, _) in declared_modules(&lib_rs) {
        let file = dir.join(format!("src/{name}.rs"));
        let sub = dir.join(format!("src/{name}"));
        let mut text = String::new();
        if file.is_file() {
            text.push_str(&read(&file));
        }
        if sub.is_dir() {
            for f in rust_files(&sub) {
                text.push('\n');
                text.push_str(&read(&f));
            }
        }
        modules.insert(name, text);
    }
    Core {
        manifest: read(&dir.join("Cargo.toml")),
        lib_rs,
        modules,
    }
}

/// Whether the CLI sources are on disk. A skip without `VIPRS_REQUIRE_CLI=1`,
/// a panic with it, exactly like `common::cli::cli_available`, except that a
/// pre-built `$VIPRS_BIN` does not count: this guard reads the CLI's source,
/// not its binary.
fn cli_source_available() -> bool {
    if cli_dir().join("Cargo.toml").is_file() {
        return true;
    }
    assert!(
        !require_cli(),
        "VIPRS_REQUIRE_CLI=1 but there is no libviprs-cli checkout at {}, so the \
         surface guard would skip and report a green that compared nothing",
        cli_dir().display()
    );
    eprintln!(
        "SKIP: no libviprs-cli checkout at {} (set $VIPRS_CLI_DIR)",
        cli_dir().display()
    );
    false
}

fn load_cli() -> Cli {
    let dir = cli_dir();
    Cli {
        manifest: read(&dir.join("Cargo.toml")),
        features_rs: read(&dir.join("src/features.rs")),
        main_rs: read(&dir.join("src/main.rs")),
        op_map: read(&dir.join("OP_MAP.md")),
    }
}

