/// Everything the CLI fails to account for, one line per item. Empty means
/// covered.
fn uncovered(core: &Core, cli: &Cli, t: &Tables) -> Vec<String> {
    let mut problems = Vec::new();
    feature_problems(core, cli, t, &mut problems);
    module_problems(core, cli, t, &mut problems);
    problems
}

fn feature_problems(core: &Core, cli: &Cli, t: &Tables, problems: &mut Vec<String>) {
    let core_features = manifest::feature_names(&core.manifest);
    let cli_features = manifest::features(&cli.manifest);
    let listed = cli_listed_features(&cli.features_rs);
    let core_table = manifest::features(&core.manifest);
    let forwarder =
        |feature: &str| manifest::forwarder(&cli_features, &core_table, feature, &["full"]);

    for feature in &core_features {
        let excluded = t.features_not_in_cli.iter().any(|(f, _)| f == feature);
        match forwarder(feature) {
            Some(cli_name) if excluded => problems.push(format!(
                "feature `{feature}`: CORE_FEATURES_NOT_IN_CLI excuses it, but the cli \
                 forwards it as `{cli_name}`. Drop the row."
            )),
            Some(cli_name) if !listed.contains(&cli_name) => problems.push(format!(
                "feature `{feature}`: the cli forwards it as `{cli_name}`, which \
                 `viprs features` does not list (src/features.rs FEATURES)"
            )),
            Some(_) => {}
            None if excluded => {}
            None => problems.push(format!(
                "feature `{feature}`: the core declares it and no libviprs-cli feature \
                 enables `libviprs/{feature}`. Forward it, or add a row to \
                 CORE_FEATURES_NOT_IN_CLI saying why the CLI has no use for it."
            )),
        }
    }
    for (feature, why) in t.features_not_in_cli {
        if !core_features.iter().any(|f| f == feature) {
            problems.push(format!(
                "feature `{feature}`: CORE_FEATURES_NOT_IN_CLI has a row for it ({why}) \
                 and the core no longer declares it. Drop or rename the row."
            ));
        }
        if why.trim().is_empty() {
            problems.push(format!(
                "feature `{feature}`: its CORE_FEATURES_NOT_IN_CLI row has no reason"
            ));
        }
    }
}

fn module_problems(core: &Core, cli: &Cli, t: &Tables, problems: &mut Vec<String>) {
    let declared = declared_modules(&core.lib_rs);
    let sections = op_map_sections(&cli.op_map);
    let builtins = cli_builtins(&cli.main_rs);
    let foreign = sections
        .get("foreign")
        .map(|s| backtick_idents(s))
        .unwrap_or_default();

    for (module, public) in &declared {
        if *public && !t.modules.iter().any(|r| r.module == module) {
            problems.push(format!(
                "module `{module}`: public in the core and MODULES says nothing about \
                 it. Add a row: its OP_MAP.md family, the codec surface, the built-in \
                 command that reaches it, or why nothing does."
            ));
        }
    }

    // Which (module, fn) pairs a scan actually looked at, so an exclusion row
    // for anything else is stale.
    let mut scanned: BTreeMap<&str, BTreeSet<String>> = BTreeMap::new();

    for r in t.modules {
        if !declared.iter().any(|(m, _)| m == r.module) {
            problems.push(format!(
                "module `{}`: MODULES has a row for it and the core's lib.rs declares \
                 no such module. Drop or rename the row.",
                r.module
            ));
            continue;
        }
        if r.why.trim().is_empty() {
            problems.push(format!(
                "module `{}`: its MODULES row has no reason",
                r.module
            ));
        }
        let src = core.modules.get(r.module).map(String::as_str).unwrap_or("");
        match r.reach {
            Reach::OpFamily(key) => {
                let Some(section) = sections.get(key) else {
                    problems.push(format!(
                        "module `{}`: MODULES points it at OP_MAP.md section `{key}`, and \
                         OP_MAP.md has no `## ... (src/{key}.rs ...)` heading",
                        r.module
                    ));
                    continue;
                };
                let idents = backtick_idents(section);
                let fns = pub_fns(src);
                for f in &fns {
                    check_fn(
                        r.module,
                        f,
                        named_in(f, &idents),
                        t,
                        problems,
                        "its OP_MAP.md family section",
                    );
                }
                scanned.insert(r.module, fns);
            }
            Reach::Codec => {
                let fns: BTreeSet<String> = pub_fns(src)
                    .into_iter()
                    .filter(|f| is_codec_entry_point(f))
                    .collect();
                for f in &fns {
                    check_fn(
                        r.module,
                        f,
                        named_in(f, &foreign),
                        t,
                        problems,
                        "OP_MAP.md's foreign section",
                    );
                }
                scanned.insert(r.module, fns);
            }
            Reach::Builtin(command) => {
                if !builtins.contains(command) {
                    problems.push(format!(
                        "module `{}`: MODULES says `viprs {command}` reaches it, and the \
                         cli's enum Command has no such built-in (has: {builtins:?})",
                        r.module
                    ));
                }
            }
            Reach::NotApplicable => {}
        }
    }

    for (module, function, why) in t.fn_exclusions {
        let Some(fns) = scanned.get(module) else {
            problems.push(format!(
                "`{module}::{function}`: FN_EXCLUSIONS has a row for it ({why}), and \
                 `{module}` is not a module this guard scans fn by fn (no OpFamily or \
                 Codec row). Drop the row."
            ));
            continue;
        };
        if !fns.contains(*function) {
            problems.push(format!(
                "`{module}::{function}`: FN_EXCLUSIONS has a row for it ({why}) and the \
                 core has no such function there any more. Drop or rename the row."
            ));
        }
        if why.trim().is_empty() {
            problems.push(format!(
                "`{module}::{function}`: its FN_EXCLUSIONS row has no reason"
            ));
        }
    }
}

fn check_fn(
    module: &str,
    function: &str,
    named: bool,
    t: &Tables,
    problems: &mut Vec<String>,
    held_to: &str,
) {
    let excluded = t
        .fn_exclusions
        .iter()
        .any(|(m, f, _)| *m == module && *f == function);
    if named && excluded {
        problems.push(format!(
            "`{module}::{function}`: FN_EXCLUSIONS excuses it, and {held_to} names it \
             after all. Drop the row."
        ));
    } else if !named && !excluded {
        problems.push(format!(
            "`{module}::{function}`: public in the core, and {held_to} does not name it. \
             Give it a viprs command and an OP_MAP.md row, or add an FN_EXCLUSIONS row \
             saying why it needs none."
        ));
    }
}

