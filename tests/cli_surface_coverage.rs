//! Fail when the core grows a capability the CLI does not account for
//! (libviprs-tests#233).
//!
//! # The hole this closes
//!
//! `libviprs-cli` drifted behind the library for two months and nothing
//! noticed. `OP_MAP.md` was audited once against core `4629599`, and every
//! feature the core gained after that landed with no `viprs` surface and no
//! test that could go red for it. Closing that gap once does nothing about the
//! next one, so this guard reads the core's surface out of the core itself and
//! asks the CLI to account for every piece of it.
//!
//! # What "account for" means
//!
//! Three things, each read from the source rather than from a hand list,
//! because a hand list is exactly what drifted:
//!
//! 1. **Capability features.** Every feature in the core's `[features]` table
//!    is forwarded by a `libviprs-cli` feature (`x = ["libviprs/x"]`) that
//!    `viprs features` lists, or has a row in [`CORE_FEATURES_NOT_IN_CLI`]
//!    saying why the CLI has no use for it. The libviprs-tests half of the same
//!    question lives in `tests/ci_feature_coverage.rs`, next to the guard that
//!    already reads this crate's `[features]` table.
//! 2. **Public modules.** Every `pub mod` in the core's `lib.rs` has a row in
//!    [`MODULES`] saying how the CLI reaches it: an op family held to its
//!    `OP_MAP.md` section, the codec surface held to `OP_MAP.md`'s foreign
//!    section, a built-in `viprs` command (checked to exist in the CLI's
//!    `enum Command`), or not at all, with the reason. A new module with no
//!    row is red.
//! 3. **Op-shaped functions.** In an op-family module every `pub fn` has to be
//!    named in that family's `OP_MAP.md` section (a row, a fold note or the
//!    section's "non-op public API" paragraph), and in a codec module every
//!    load/save entry point has to be named in the foreign section, or sit in
//!    [`FN_EXCLUSIONS`] with a one-line reason.
//!
//! Every exclusion row is checked as hard as the surface is. A row for a
//! feature, module or function the core no longer has is red, and so is a row
//! for something the CLI turns out to cover after all, so renaming an excluded
//! item without touching the list fails here instead of leaving a row that
//! excuses nothing.
//!
//! # Where the facts come from
//!
//! All offline. The core is the `../libviprs` path dependency this crate
//! compiles against, which CI checks out at `COUNTERPART_REV`. The CLI is the
//! `../libviprs-cli` sibling (`$VIPRS_CLI_DIR` wins), which CI checks out at
//! `CLI_COUNTERPART_REV`: its `Cargo.toml`, the `FEATURES` table in
//! `src/features.rs` (exactly what `viprs features --json` prints), the
//! `enum Command` in `src/main.rs`, and `OP_MAP.md`. Without the CLI sibling
//! the CLI half skips, and `VIPRS_REQUIRE_CLI=1` turns that skip into a
//! failure, the same discipline as every CLI differential cell.
//!
//! # What it deliberately does not do
//!
//! It does not judge whether a mapping is any good. `OP_MAP.md` naming a
//! function is enough to pass here; whether the command behaves like vips is
//! the differential cells' job. It reads `pub fn` lines from rustfmt'd source,
//! so a function generated by a macro is invisible to it. And modules marked
//! as reached through a built-in are accounted for as a whole: a new builder
//! setter on the engine is a flag question for `viprs pyramid`, not a missing
//! op, and this guard does not try to tell the two apart.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

mod common;
use common::cli::{cli_dir, require_cli};
use common::manifest;

// ---------------------------------------------------------------------------
// The tables. Data, reviewed like code: every row carries its reason.
// ---------------------------------------------------------------------------

/// How the CLI reaches one public core module.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Reach {
    /// An op family: every `pub fn` in the module is held to the `OP_MAP.md`
    /// section with this key (the `src/<key>.rs` its heading names).
    OpFamily(&'static str),
    /// Part of the codec surface: every load/save entry point in the module is
    /// held to `OP_MAP.md`'s foreign section.
    Codec,
    /// Reached through this built-in `viprs` command, which is not an op and
    /// so has no `OP_MAP.md` row. The command has to exist in the CLI.
    Builtin(&'static str),
    /// Nothing in the CLI reaches it, on purpose.
    NotApplicable,
}

/// One row of [`MODULES`].
struct ModuleRow {
    module: &'static str,
    reach: Reach,
    why: &'static str,
}

const fn row(module: &'static str, reach: Reach, why: &'static str) -> ModuleRow {
    ModuleRow { module, reach, why }
}

/// Every public core module, and how the CLI reaches it.
const MODULES: &[ModuleRow] = &[];

/// `(module, fn, reason)`: a function in an op-family or codec module that
/// `OP_MAP.md` does not name, and why it needs no `viprs` surface.
const FN_EXCLUSIONS: &[(&str, &str, &str)] = &[];

/// `(feature, reason)`: a core capability feature the CLI does not forward.
const CORE_FEATURES_NOT_IN_CLI: &[(&str, &str)] = &[];

/// The tables one check runs against. The real run uses the consts above; the
/// controls pass synthetic ones so they test the checker, not today's data.
struct Tables<'a> {
    modules: &'a [ModuleRow],
    fn_exclusions: &'a [(&'a str, &'a str, &'a str)],
    features_not_in_cli: &'a [(&'a str, &'a str)],
}

const REAL: Tables<'static> = Tables {
    modules: MODULES,
    fn_exclusions: FN_EXCLUSIONS,
    features_not_in_cli: CORE_FEATURES_NOT_IN_CLI,
};

// ---------------------------------------------------------------------------
// The two trees, read from disk.
