/// `(module, is_pub)` for every `mod` item at the top of `lib.rs`.
///
/// `pub(crate) mod` and plain `mod` are declared but not public. They are
/// returned so a [`MODULES`] row for one is not mistaken for a stale row (the
/// core's `raster_ops` is `pub(crate)`, yet its `Raster` methods are public
/// and `OP_MAP.md` has a section for it).
fn declared_modules(lib_rs: &str) -> Vec<(String, bool)> {
    lib_rs
        .lines()
        .filter_map(|line| {
            let (rest, public) = if let Some(r) = line.strip_prefix("pub mod ") {
                (r, true)
            } else if let Some(r) = line.strip_prefix("pub(crate) mod ") {
                (r, false)
            } else {
                (line.strip_prefix("mod ")?, false)
            };
            let name = rest.strip_suffix(';')?.trim();
            is_ident(name).then(|| (name.to_string(), public))
        })
        .collect()
}

fn is_ident(s: &str) -> bool {
    !s.is_empty()
        && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        && !s.starts_with(|c: char| c.is_ascii_digit())
}

/// Every `pub fn` name in `src`, free functions and methods alike, with test
/// code left out.
///
/// Relies on rustfmt layout: a `#[cfg(test)]` item ends at the first line that
/// is its own indentation followed by `}`. Visibility-restricted functions
/// (`pub(crate) fn`) are not public and are not returned.
fn pub_fns(src: &str) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    let mut skip_until: Option<String> = None;
    let mut test_attr_indent: Option<String> = None;
    for line in src.lines() {
        if let Some(end) = &skip_until {
            if line == end {
                skip_until = None;
            }
            continue;
        }
        let trimmed = line.trim_start();
        let indent = &line[..line.len() - trimmed.len()];
        if trimmed.starts_with("#[cfg(test)]") || trimmed.starts_with("#[cfg(all(test") {
            test_attr_indent = Some(indent.to_string());
            continue;
        }
        if let Some(attr_indent) = test_attr_indent.take() {
            if trimmed.starts_with("#[") || trimmed.starts_with("///") {
                test_attr_indent = Some(attr_indent);
                continue;
            }
            if trimmed.trim_end().ends_with('{') {
                skip_until = Some(format!("{attr_indent}}}"));
            }
            continue;
        }
        let mut rest = match trimmed.strip_prefix("pub ") {
            Some(r) => r,
            None => continue,
        };
        for qualifier in ["const ", "unsafe ", "async ", "extern \"C\" "] {
            if let Some(r) = rest.strip_prefix(qualifier) {
                rest = r;
            }
        }
        if let Some(r) = rest.strip_prefix("fn ") {
            let name: String = r
                .chars()
                .take_while(|c| c.is_ascii_alphanumeric() || *c == '_')
                .collect();
            if is_ident(&name) {
                out.insert(name);
            }
        }
    }
    out
}

/// `OP_MAP.md` split at its `## ` headings, keyed by the first `src/<x>.rs`
/// the heading names (`## colour (src/colour.rs: ...)` is `colour`), or by the
/// heading's first word when it names no source file (`## foreign (...)` is
/// `foreign`).
fn op_map_sections(op_map: &str) -> BTreeMap<String, String> {
    let mut out: BTreeMap<String, String> = BTreeMap::new();
    let mut key: Option<String> = None;
    for line in op_map.lines() {
        if let Some(heading) = line.strip_prefix("## ") {
            let from_src = heading.split("src/").nth(1).and_then(|r| {
                let name: String = r
                    .chars()
                    .take_while(|c| c.is_ascii_alphanumeric() || *c == '_')
                    .collect();
                r[name.len()..].starts_with(".rs").then_some(name)
            });
            let k = from_src.unwrap_or_else(|| {
                heading
                    .split_whitespace()
                    .next()
                    .unwrap_or("")
                    .to_ascii_lowercase()
            });
            key = Some(k);
        }
        if let Some(k) = &key {
            let section = out.entry(k.clone()).or_default();
            section.push_str(line);
            section.push('\n');
        }
    }
    out
}

/// Every identifier inside backticks in `text`, with `a::with_{x, y}` brace
/// lists expanded, because that is how `OP_MAP.md` names a run of setters.
fn backtick_idents(text: &str) -> BTreeSet<String> {
    fn expand(s: &str) -> Vec<String> {
        let Some(open) = s.find('{') else {
            return vec![s.to_string()];
        };
        let Some(close) = s[open..].find('}').map(|c| open + c) else {
            return vec![s.to_string()];
        };
        let (head, alts, tail) = (&s[..open], &s[open + 1..close], &s[close + 1..]);
        alts.split(',')
            .flat_map(|alt| expand(&format!("{head}{}{tail}", alt.trim())))
            .collect()
    }
    let mut out = BTreeSet::new();
    for (i, chunk) in text.split('`').enumerate() {
        if i % 2 == 0 {
            continue;
        }
        for expanded in expand(&chunk.replace('\n', " ")) {
            let mut cur = String::new();
            for ch in expanded.chars().chain(std::iter::once(' ')) {
                if ch.is_ascii_alphanumeric() || ch == '_' {
                    cur.push(ch);
                } else if !cur.is_empty() {
                    if is_ident(&cur) {
                        out.insert(std::mem::take(&mut cur));
                    } else {
                        cur.clear();
                    }
                }
            }
        }
    }
    out
}

/// Whether `OP_MAP.md` names `function`, directly or through the dedup rules
/// its legend states: a `try_*` twin folds into its base, an option variant
/// (`x_with`, `x_with_profile`, ...) folds into `x` and `x` into a row that
/// only names `x_with`, `_filled` folds into the outline form, and a file
/// `save_x` is the same row as its `encode_x`.
fn named_in(function: &str, idents: &BTreeSet<String>) -> bool {
    let mut candidates = vec![function.to_string()];
    if let Some(base) = function.strip_prefix("try_") {
        candidates.push(base.to_string());
    }
    for c in candidates.clone() {
        if let Some(at) = c.find("_with") {
            candidates.push(c[..at].to_string());
        }
        if let Some(base) = c.strip_suffix("_filled") {
            candidates.push(base.to_string());
        }
        if let Some(base) = c.strip_prefix("save_") {
            candidates.push(format!("encode_{base}"));
        }
    }
    candidates.iter().any(|c| {
        idents.contains(c)
            || idents.iter().any(|id| {
                id.strip_prefix(c.as_str())
                    .is_some_and(|t| t.starts_with("_with"))
            })
    })
}

/// Whether a codec-module function is a load or save entry point, the only
/// shape the foreign section is about. Option setters and probes in those
/// modules are not, and the module's [`MODULES`] row covers them.
fn is_codec_entry_point(function: &str) -> bool {
    function.starts_with("decode")
        || function.starts_with("encode")
        || function.starts_with("save")
        || function.contains("load")
        || function.contains("save")
}

/// The built-in commands in the CLI's `enum Command`, kebab-cased the way
/// clap derives them (`TestImage` is `test-image`). The op families are
/// assembled elsewhere and are `OP_MAP.md`'s business, not this list's.
fn cli_builtins(main_rs: &str) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    let mut inside = false;
    for line in main_rs.lines() {
        if line.starts_with("enum Command {") || line.starts_with("pub enum Command {") {
            inside = true;
            continue;
        }
        if !inside {
            continue;
        }
        if line == "}" {
            break;
        }
        let Some(rest) = line.strip_prefix("    ") else {
            continue;
        };
        if !rest.starts_with(|c: char| c.is_ascii_uppercase()) {
            continue;
        }
        let variant: String = rest
            .chars()
            .take_while(|c| c.is_ascii_alphanumeric())
            .collect();
        let mut kebab = String::new();
        for (i, ch) in variant.chars().enumerate() {
            if ch.is_ascii_uppercase() {
                if i > 0 {
                    kebab.push('-');
                }
                kebab.push(ch.to_ascii_lowercase());
            } else {
                kebab.push(ch);
            }
        }
        out.insert(kebab);
    }
    out
}

/// The names in the CLI's `FEATURES` table, which is what `viprs features`
/// prints (`("jxl", cfg!(feature = "jxl"))` rows).
fn cli_listed_features(features_rs: &str) -> BTreeSet<String> {
    features_rs
        .lines()
        .filter_map(|line| {
            let rest = line.trim().strip_prefix("(\"")?;
            let (name, tail) = rest.split_once('"')?;
            tail.contains("cfg!(feature").then(|| name.to_string())
        })
        .collect()
}

