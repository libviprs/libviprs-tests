/// A minimal CLI that covers nothing but what each control sets up.
fn synthetic_cli(op_map: &str) -> Cli {
    Cli {
        manifest: "[features]\nfull = [\"jxl\"]\njxl = [\"libviprs/jxl\"]\n".to_string(),
        features_rs: "const FEATURES: &[(&str, bool)] = &[\n    (\"jxl\", cfg!(feature = \"jxl\")),\n];\n"
            .to_string(),
        main_rs: "enum Command {\n    /// doc\n    Pyramid(Box<PyramidArgs>),\n    TestImage(TestImageArgs),\n}\n"
            .to_string(),
        op_map: op_map.to_string(),
    }
}

/// A core with exactly the pieces a control names: one op family, one codec
/// module, one built-in module, and the given features.
fn synthetic_core(features: &str, arithmetic: &str) -> Core {
    let lib_rs =
        "pub mod arithmetic;\npub mod gif;\npub mod engine;\npub(crate) mod hex;\n".to_string();
    let mut modules = BTreeMap::new();
    modules.insert("arithmetic".to_string(), arithmetic.to_string());
    modules.insert(
        "gif".to_string(),
        "pub fn decode_gif() {}\npub fn decode_gif_with() {}\nimpl O { pub fn with_dither(self) {} }\n"
            .to_string(),
    );
    modules.insert(
        "engine".to_string(),
        "pub fn generate_pyramid() {}\n".to_string(),
    );
    modules.insert("hex".to_string(), String::new());
    Core {
        manifest: format!("[features]\ndefault = []\n{features}"),
        lib_rs,
        modules,
    }
}

const SYNTH_OP_MAP: &str = "\
## arithmetic (src/arithmetic.rs: 2 pub fns)\n\
| `abs` | `abs` | S1 | EXACT | `try_abs` folds |\n\
## foreign (codec load/save)\n\
| `decode_gif_with` | `gifload` | EXACT | | |\n";

const SYNTH_MODULES: &[ModuleRow] = &[
    row(
        "arithmetic",
        Reach::OpFamily("arithmetic"),
        "the arithmetic family",
    ),
    row("gif", Reach::Codec, "the GIF codec"),
    row(
        "engine",
        Reach::Builtin("pyramid"),
        "viprs pyramid drives the engine",
    ),
    row(
        "hex",
        Reach::NotApplicable,
        "crate-private, listed to show a row may name one",
    ),
];

const SYNTH_ARITH: &str = "impl Raster {\n    pub fn abs(&self) {}\n    pub fn try_abs(&self) {}\n}\n\
#[cfg(test)]\nmod tests {\n    pub fn not_public_api() {}\n}\n";

fn synth_tables<'a>(
    fn_exclusions: &'a [(&'a str, &'a str, &'a str)],
    features_not_in_cli: &'a [(&'a str, &'a str)],
) -> Tables<'a> {
    Tables {
        modules: SYNTH_MODULES,
        fn_exclusions,
        features_not_in_cli,
    }
}

/// The synthetic baseline is covered, so every control below starts green and
/// the red it reports is the mutation's, not the scaffolding's.
#[test]
fn control_the_synthetic_baseline_is_covered() {
    let core = synthetic_core("jxl = [\"dep:x\"]\nserde = []\n", SYNTH_ARITH);
    let cli = synthetic_cli(SYNTH_OP_MAP);
    let t = synth_tables(&[], &[("serde", "derives only")]);
    assert_eq!(uncovered(&core, &cli, &t), Vec::<String>::new());
}

/// Positive control: a new `pub fn` in an op family turns the guard red and
/// names it, and taking it away turns it green again.
#[test]
fn control_a_new_pub_fn_in_an_op_family_is_red_until_removed() {
    let cli = synthetic_cli(SYNTH_OP_MAP);
    let t = synth_tables(&[], &[]);
    let grown = SYNTH_ARITH.replace(
        "    pub fn try_abs(&self) {}\n",
        "    pub fn try_abs(&self) {}\n    pub fn zz_synthetic_capability(&self) {}\n",
    );
    let red = uncovered(&synthetic_core("", &grown), &cli, &t);
    assert!(
        red.len() == 1 && red[0].contains("arithmetic::zz_synthetic_capability"),
        "a new op-family fn must be the one thing named, got {red:#?}"
    );
    let green = uncovered(&synthetic_core("", SYNTH_ARITH), &cli, &t);
    assert!(
        green.is_empty(),
        "removing it must turn green, got {green:#?}"
    );

    // The same on the real core text: arithmetic.rs as it is today plus one
    // function, against a section that names everything else in it.
    let real = load_core();
    let arith = real.modules.get("arithmetic").cloned().unwrap_or_default();
    let mut names: Vec<String> = pub_fns(&arith).into_iter().collect();
    names.sort();
    let section = format!(
        "## arithmetic (src/arithmetic.rs)\n{}\n## foreign\n| `decode_gif_with` |\n",
        names
            .iter()
            .map(|n| format!("`{n}`"))
            .collect::<Vec<_>>()
            .join(" ")
    );
    let cli = synthetic_cli(&section);
    let base = uncovered(&synthetic_core("", &arith), &cli, &t);
    assert!(
        base.is_empty(),
        "today's arithmetic.rs against its own names: {base:#?}"
    );
    let grown =
        format!("{arith}\nimpl Raster {{\n    pub fn zz_synthetic_capability(&self) {{}}\n}}\n");
    let red = uncovered(&synthetic_core("", &grown), &cli, &t);
    assert!(
        red.len() == 1 && red[0].contains("zz_synthetic_capability"),
        "a dummy pub fn added to today's arithmetic.rs must be named, got {red:#?}"
    );
}

/// Positive control: a new codec entry point, a new public module and a new
/// capability feature are each red and named.
#[test]
fn control_a_new_codec_module_or_feature_is_red() {
    let cli = synthetic_cli(SYNTH_OP_MAP);
    let t = synth_tables(&[], &[]);

    let mut core = synthetic_core("", SYNTH_ARITH);
    core.modules
        .get_mut("gif")
        .unwrap()
        .push_str("pub fn save_gif_animated() {}\n");
    let red = uncovered(&core, &cli, &t);
    assert!(
        red.len() == 1 && red[0].contains("gif::save_gif_animated"),
        "a new codec entry point must be named, got {red:#?}"
    );

    let mut core = synthetic_core("", SYNTH_ARITH);
    core.lib_rs.push_str("pub mod zz_synthetic;\n");
    core.modules
        .insert("zz_synthetic".into(), "pub fn op() {}\n".into());
    let red = uncovered(&core, &cli, &t);
    assert!(
        red.len() == 1 && red[0].contains("module `zz_synthetic`"),
        "a new public module must be named, got {red:#?}"
    );

    let core = synthetic_core("zz-synthetic = [\"dep:x\"]\n", SYNTH_ARITH);
    let red = uncovered(&core, &cli, &t);
    assert!(
        red.len() == 1 && red[0].contains("feature `zz-synthetic`"),
        "a new core feature must be named, got {red:#?}"
    );

    // And on the real manifest: today's core features plus one.
    let real = load_core();
    let real_cli_features: Vec<String> = manifest::feature_names(&real.manifest);
    let fwd: String = real_cli_features
        .iter()
        .map(|f| format!("{f} = [\"libviprs/{f}\"]\n"))
        .collect();
    let listed: String = real_cli_features
        .iter()
        .map(|f| format!("    (\"{f}\", cfg!(feature = \"{f}\")),\n"))
        .collect();
    let mut cli = synthetic_cli(SYNTH_OP_MAP);
    cli.manifest = format!("[features]\n{fwd}");
    cli.features_rs = format!("const FEATURES: &[(&str, bool)] = &[\n{listed}];\n");
    let mut core = synthetic_core("", SYNTH_ARITH);
    core.manifest = real.manifest.clone();
    assert!(uncovered(&core, &cli, &t).is_empty());
    core.manifest = real
        .manifest
        .replacen("[features]\n", "[features]\nzz-synthetic = []\n", 1);
    let red = uncovered(&core, &cli, &t);
    assert!(
        red.len() == 1 && red[0].contains("feature `zz-synthetic`"),
        "a feature added to today's core manifest must be named, got {red:#?}"
    );
}

/// Negative control: renaming an excluded item without updating the list is
/// red, so the list cannot rot into rows that excuse nothing.
#[test]
fn control_a_renamed_excluded_item_is_red() {
    let cli = synthetic_cli(SYNTH_OP_MAP);

    // A module row whose module was renamed: the stale row and the new,
    // unaccounted module are both named.
    let core = synthetic_core("", SYNTH_ARITH);
    let mut renamed = core.clone();
    renamed.lib_rs = renamed
        .lib_rs
        .replace("pub mod engine;", "pub mod engine2;");
    renamed.modules.insert("engine2".into(), String::new());
    let red = uncovered(&renamed, &cli, &synth_tables(&[], &[]));
    assert!(
        red.iter()
            .any(|p| p.contains("module `engine`") && p.contains("no such module"))
            && red.iter().any(|p| p.contains("module `engine2`")),
        "a renamed module must name the stale row and the new module, got {red:#?}"
    );

    // A feature exclusion whose feature was renamed.
    let core = synthetic_core("serde-derive = []\n", SYNTH_ARITH);
    let red = uncovered(
        &core,
        &cli,
        &synth_tables(&[], &[("serde", "derives only")]),
    );
    assert!(
        red.iter()
            .any(|p| p.contains("feature `serde`") && p.contains("no longer declares"))
            && red.iter().any(|p| p.contains("feature `serde-derive`")),
        "a renamed feature must name the stale row and the new feature, got {red:#?}"
    );

    // A fn exclusion whose fn was renamed.
    let arith = SYNTH_ARITH.replace(
        "    pub fn try_abs(&self) {}\n",
        "    pub fn try_abs(&self) {}\n    pub fn helper2(&self) {}\n",
    );
    let core = synthetic_core("", &arith);
    let red = uncovered(
        &core,
        &cli,
        &synth_tables(&[("arithmetic", "helper", "internal")], &[]),
    );
    assert!(
        red.iter()
            .any(|p| p.contains("arithmetic::helper`") && p.contains("no such function"))
            && red.iter().any(|p| p.contains("arithmetic::helper2")),
        "a renamed fn must name the stale row and the new fn, got {red:#?}"
    );

    // An exclusion for something the CLI covers after all is red too.
    let core = synthetic_core("jxl = [\"dep:x\"]\n", SYNTH_ARITH);
    let red = uncovered(
        &core,
        &cli,
        &synth_tables(&[("arithmetic", "abs", "x")], &[("jxl", "y")]),
    );
    assert!(
        red.iter()
            .any(|p| p.contains("arithmetic::abs") && p.contains("Drop the row"))
            && red
                .iter()
                .any(|p| p.contains("feature `jxl`") && p.contains("Drop the row")),
        "an exclusion for a covered item must be red, got {red:#?}"
    );
}

/// The readers parse the shapes they will meet.
#[test]
fn control_the_readers_read_what_they_say() {
    // pub fns: methods and free fns, qualifiers, no pub(crate), no test code.
    let src = "pub fn a() {}\npub(crate) fn b() {}\nimpl X {\n    pub const fn c() {}\n    pub unsafe fn d() {}\n    fn e() {}\n    #[cfg(test)]\n    pub fn f() {}\n}\n#[cfg(test)]\nmod tests {\n    pub fn g() {}\n}\npub fn h<T>(t: T) {}\n";
    let got: Vec<String> = pub_fns(src).into_iter().collect();
    assert_eq!(got, ["a", "c", "d", "h"]);

    // Brace lists expand; prose outside backticks does not count.
    let ids = backtick_idents("`AffineOptions::with_{odx,\nody}` and `x` but not y");
    assert!(ids.contains("with_odx") && ids.contains("with_ody") && ids.contains("x"));
    assert!(!ids.contains("y"));

    // Folds the OP_MAP legend states, and nothing broader.
    let ids: BTreeSet<String> = ["abs", "decode_gif_with", "encode_png", "draw_rect"]
        .into_iter()
        .map(String::from)
        .collect();
    for yes in [
        "try_abs",
        "abs_with",
        "decode_gif",
        "save_png",
        "draw_rect_filled",
    ] {
        assert!(named_in(yes, &ids), "{yes} should fold into a named row");
    }
    for no in ["absolute", "decode", "encode_jpeg", "zz_abs"] {
        assert!(!named_in(no, &ids), "{no} must not fold into a named row");
    }

    // Built-ins kebab-case; features read from the FEATURES rows only.
    let cli = synthetic_cli("");
    let builtins: Vec<String> = cli_builtins(&cli.main_rs).into_iter().collect();
    assert_eq!(builtins, ["pyramid", "test-image"]);
    let listed: Vec<String> = cli_listed_features(&cli.features_rs).into_iter().collect();
    assert_eq!(listed, ["jxl"]);

    // A multi-line feature array reads whole.
    let m = "[package]\nname = \"x\"\n[features]\ndefault = [\"a\"]\nfull = [\n    \"a\", # c\n    \"b\",\n]\na = [\"libviprs/a\"] # trailing\n[dependencies]\nz = \"1\"\n";
    let fs = manifest::features(m);
    let names: Vec<&str> = fs.iter().map(|f| f.name.as_str()).collect();
    assert_eq!(names, ["default", "full", "a"]);
    assert_eq!(fs[1].enables, ["a", "b"]);
    assert_eq!(fs[2].enables, ["libviprs/a"]);

    // A pure core alias is reached through what it aliases; anything else
    // has to be forwarded by name.
    let core = manifest::features(
        "[features]\nosink = []\ns3 = [\"osink\"]\npdfium = [\"dep:p\"]\npdfium-static = [\"pdfium\", \"p/static\"]\n",
    );
    let ours = manifest::features(
        "[features]\nfull = [\"libviprs/pdfium-static\"]\nosink = [\"libviprs/osink\"]\ns3 = [\"osink\"]\npdfium = [\"libviprs/pdfium\"]\n",
    );
    let fwd = |f: &str| manifest::forwarder(&ours, &core, f, &["full"]);
    assert_eq!(fwd("osink").as_deref(), Some("osink"));
    assert_eq!(fwd("s3").as_deref(), Some("osink"));
    assert_eq!(fwd("pdfium").as_deref(), Some("pdfium"));
    assert_eq!(
        fwd("pdfium-static"),
        None,
        "a bundle does not count, and pdfium-static is no alias"
    );
}
